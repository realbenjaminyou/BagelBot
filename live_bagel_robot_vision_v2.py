def clip_box(coords,W,H):
    x1,y1,x2,y2=[int(round(v)) for v in coords]
    return (max(0,min(W-2,x1)),max(0,min(H-2,y1)),max(1,min(W,x2)),max(1,min(H,y2)))


def iou(a,b):
    x=max(0,min(a[2],b[2])-max(a[0],b[0])); y=max(0,min(a[3],b[3])-max(a[1],b[1]))
    inter=x*y
    return inter/max(1,(a[2]-a[0])*(a[3]-a[1])+(b[2]-b[0])*(b[3]-b[1])-inter)


def feature_channels(image):
    lab=cv2.cvtColor(image,cv2.COLOR_BGR2LAB).astype(np.float32)/255.
    hsv=cv2.cvtColor(image,cv2.COLOR_BGR2HSV).astype(np.float32)
    hsv[:,:,1:]/=255.
    gray=cv2.cvtColor(image,cv2.COLOR_BGR2GRAY).astype(np.float32)/255.
    mean=cv2.GaussianBlur(gray,(5,5),0)
    m11=cv2.GaussianBlur(gray,(11,11),0)
    s=np.sqrt(np.maximum(0,cv2.GaussianBlur(gray*gray,(5,5),0)-mean*mean))
    s11=np.sqrt(np.maximum(0,cv2.GaussianBlur(gray*gray,(11,11),0)-m11*m11))
    gx=cv2.Sobel(gray,cv2.CV_32F,1,0,ksize=3)
    gy=cv2.Sobel(gray,cv2.CV_32F,0,1,ksize=3)
    edge=np.minimum(2,cv2.magnitude(gx,gy))
    lap=np.minimum(2,np.abs(cv2.Laplacian(gray,cv2.CV_32F,ksize=3)))
    return np.dstack((lab,hsv[:,:,1:3],mean,s,s11,edge,lap)).astype(np.float32)


class SurfaceClassifier:
    """Fast locally pretrained OpenCV forest: no user input / no CLIP patch loop."""
    def __init__(self,resolution=220):
        self.res=resolution
        self.forest=cv2.ml.RTrees_create()
        self.forest.setMaxDepth(12)
        self.forest.setMinSampleCount(5)
        self.forest.setActiveVarCount(6)
        self.forest.setTermCriteria((cv2.TERM_CRITERIA_MAX_ITER,50,0))
        rng=np.random.default_rng(21); xs=[];ys=[]
        for name,label in [('SPREAD_TOP',1),('SPREAD_RIDGE',1),('SPREAD_SIDE',1),
                           ('SPREAD_LIGHT',1),('BARE_BOTTOM',0),('BARE_LEFT',0),
                           ('BARE_PLAIN',0),('BARE_PLAIN2',0),('BARE_FIRST',0)]:
            img=decode_ref(name)
            if img is None:continue
            h,w=img.shape[:2]
            f=feature_channels(img)[int(.16*h):int(.84*h),int(.16*w):int(.84*w)].reshape(-1,10)
            ix=rng.choice(len(f),size=min(400,len(f)),replace=False)
            xs.append(f[ix]);ys.append(np.full(len(ix),label,np.int32))
        if not xs:raise RuntimeError('Embedded bread reference samples missing')
        data=np.concatenate(xs).astype(np.float32);labels=np.concatenate(ys)
        self.forest.train(data,cv2.ml.ROW_SAMPLE,labels)
        pos=data[labels==1];neg=data[labels==0]
        self.mu_p=np.median(pos,axis=0);self.mu_n=np.median(neg,axis=0)
        self.scale_p=np.maximum(np.percentile(abs(pos-self.mu_p),75,axis=0),.02)
        self.scale_n=np.maximum(np.percentile(abs(neg-self.mu_n),75,axis=0),.02)

    def analyze(self,frame,box,sensitivity=.56):
        x1,y1,x2,y2=box;crop=frame[y1:y2,x1:x2]
        if crop.size==0 or min(crop.shape[:2])<35:return None
        h,w=crop.shape[:2];sc=min(1.,self.res/max(h,w));sw=max(30,round(w*sc));sh=max(30,round(h*sc))
        im=cv2.resize(crop,(sw,sh),interpolation=cv2.INTER_AREA)
        feat=feature_channels(im);flat=feat.reshape(-1,10)
        _,pred=self.forest.predict(flat)
        rf=pred.reshape(sh,sw)>0.5
        # Dynamic reference comparison uses both chroma and microtexture.
        cols=[0,1,2,3,4,6,7,8]
        dp=np.mean(np.minimum(((flat[:,cols]-self.mu_p[cols])/self.scale_p[cols])**2,16),axis=1).reshape(sh,sw)
        dn=np.mean(np.minimum(((flat[:,cols]-self.mu_n[cols])/self.scale_n[cols])**2,16),axis=1).reshape(sh,sw)
        appearance=1/(1+np.exp(-np.clip(.18*(dn-dp),-12,12)))
        kernel3=cv2.getStructuringElement(cv2.MORPH_ELLIPSE,(3,3))
        candidate=(appearance>=sensitivity) | (rf&(appearance>=sensitivity-.16))
        # Gentle closing joins cream-cheese ridges without erasing thin smears.
        mask=cv2.morphologyEx(candidate.astype(np.uint8),cv2.MORPH_CLOSE,kernel3)
        mask=cv2.medianBlur((mask*255).astype(np.uint8),3)
        yy,xx=np.ogrid[:sh,:sw]
        shape=(((xx-(sw-1)/2)/max(1,.47*sw))**2+((yy-(sh-1)/2)/max(1,.47*sh))**2<=1)
        # Only excise an obvious dark central opening, not the whole center.
        gray=cv2.cvtColor(im,cv2.COLOR_BGR2GRAY)
        center=(((xx-sw/2)/max(1,.19*sw))**2+((yy-sh/2)/max(1,.19*sh))**2<1)
        holes=cv2.morphologyEx(((gray<48)&center).astype(np.uint8),cv2.MORPH_OPEN,kernel3)
        if 8<np.count_nonzero(holes)<.07*sw*sh:shape[holes>0]=False
        total=int(np.count_nonzero(shape));covered=int(np.count_nonzero((mask>0)&shape))
        return (cv2.resize(mask,(w,h),interpolation=cv2.INTER_NEAREST),
                cv2.resize((shape*255).astype(np.uint8),(w,h),interpolation=cv2.INTER_NEAREST),
                round(100*covered/max(1,total)))


class AppearanceGuard:
    """Verify material/geometry BEFORE assigning bagel versus plastic tub."""
    def __init__(self):
        self.orb=cv2.ORB_create(nfeatures=350,fastThreshold=9)
        self.matcher=cv2.BFMatcher(cv2.NORM_HAMMING)
        self.tubs=[]
        for name in ('28','29','30','31','32'):
            img=decode_ref(name)
            if img is None:continue
            _,des=self.orb.detectAndCompute(cv2.cvtColor(img,cv2.COLOR_BGR2GRAY),None)
            if des is not None:self.tubs.append(des)
        self.bread_samples=[]
        for name in ('BARE_PLAIN','BARE_FIRST','BARE_BOTTOM','SPREAD_TOP'):
            im=decode_ref(name)
            if im is not None:
                lab=cv2.cvtColor(im,cv2.COLOR_BGR2LAB)
                self.bread_samples.append(np.median(lab.reshape(-1,3),axis=0))

    def inspect(self,frame,box):
        x1,y1,x2,y2=box;roi=frame[y1:y2,x1:x2]
        if roi.size==0:return {'bread':0.,'tub':0.,'matches':0,'hole':False}
        small=cv2.resize(roi,(min(170,roi.shape[1]),min(170,roi.shape[0])))
        lab=cv2.cvtColor(small,cv2.COLOR_BGR2LAB)
        gray=cv2.cvtColor(small,cv2.COLOR_BGR2GRAY)
        hh,ww=gray.shape; core=lab[hh//6:5*hh//6,ww//6:5*ww//6]
        # Bread is porous, with a beige/gold cut face, not smooth gray plastic.
        # Lighting-independent reference chroma distance, backed by edge texture.
        chroma=core[:,:,1:3].astype(np.float32)
        bread=np.clip((chroma[:,:,1]-137.)/15.,0.,1.)
        bread_fraction=float(np.mean(bread>.15))
        porous=float(np.mean(cv2.Canny(gray,35,100)>0))
        bread_score=min(1.,.74*bread_fraction+.26*np.clip(porous/.14,0,1))
        # Dark center aperture is useful supporting evidence, not mandatory.
        mid=gray[hh//3:2*hh//3,ww//3:2*ww//3]
        hole=bool(mid.size and np.mean(mid<65)>.035 and bread_fraction>.25)
        if hole:bread_score=min(1.,bread_score+.11)
        plastic=np.mean(chroma[:,:,1]<141)
        _,des=self.orb.detectAndCompute(gray,None)
        match_count=0
        if des is not None:
            for ref in self.tubs:
                pairs=self.matcher.knnMatch(des,ref,k=2)
                good=sum(1 for pair in pairs if len(pair)==2 and pair[0].distance<.72*pair[1].distance)
                match_count=max(good,match_count)
        tub_score=min(1.,.53*float(plastic)+.47*min(1.,match_count/10.))
        # Do not claim a tub because an object is circular: bagels are circular too.
        if bread_score>.55 and match_count<8:tub_score*=.35
        return {'bread':bread_score,'tub':tub_score,'matches':match_count,'hole':hole}


def center(box):return ((box[0]+box[2])//2,(box[1]+box[3])//2)


def distance_to_rect(point,box):
    x,y=point;x1,y1,x2,y2=box
    dx=max(x1-x,0,x-x2);dy=max(y1-y,0,y-y2)
    return math.hypot(dx,dy)


def candidate_knife_lines(frame, search_box, bagel=None):
    """Find long, thin line candidates near the gripper; excludes tiny cable fragments.
    A line candidate is never certified as a real knife or contact signal.
    """
    H,W=frame.shape[:2]
    x1,y1,x2,y2=search_box
    pad=int(max(x2-x1,y2-y1)*.55)
    xa=max(0,x1-pad);ya=max(0,y1-pad);xb=min(W,x2+pad);yb=min(H,y2+pad)
    roi=frame[ya:yb,xa:xb]
    if roi.size==0:return None
    gray=cv2.cvtColor(roi,cv2.COLOR_BGR2GRAY)
    edges=cv2.Canny(gray,65,150)
    min_length=max(25,int(.17*max(xb-xa,yb-ya)))
    lines=cv2.HoughLinesP(edges,1,np.pi/180,threshold=30,
                          minLineLength=min_length,maxLineGap=10)
    if lines is None:return None
    best=None;bestscore=-1
    for v in lines[:,0]:
        ax,ay,bx,by=map(int,v);length=math.hypot(ax-bx,ay-by)
        p1=(xa+ax,ya+ay);p2=(xa+bx,ya+by)
        # Prefer lines attached to claw and pointing towards bagel.
        dc=min(distance_to_rect(p1,search_box),distance_to_rect(p2,search_box))
        if dc>45:continue
        score=length/(1+dc*.03)
        if bagel is not None:
            score+=max(0,50-min(distance_to_rect(p1,bagel),distance_to_rect(p2,bagel)))*.2
        if score>bestscore:best=(p1,p2);bestscore=score
    return best


def gripper_fallback(frame):
    """Find green fingertip tape next to white printed gripper parts.
    Returns a *candidate*, not positive robot-part identification.
    """
    hsv=cv2.cvtColor(frame,cv2.COLOR_BGR2HSV)
    green=cv2.inRange(hsv,(35,55,32),(95,255,255))
    green=cv2.morphologyEx(green,cv2.MORPH_OPEN,np.ones((3,3),np.uint8))
    count,labels,stats,centroids=cv2.connectedComponentsWithStats(green)
    H,W=frame.shape[:2];possible=[]
    for i in range(1,count):
        x,y,w,h,area=stats[i]
        if area<18 or area>2500 or w>W*.24 or h>H*.24:continue
        # Require nearby bright low-saturation plastic, not green alone.
        x1=max(0,x-55);y1=max(0,y-55);x2=min(W,x+w+55);y2=min(H,y+h+55)
        hood=hsv[y1:y2,x1:x2]
        white=((hood[:,:,1]<85)&(hood[:,:,2]>125))
        if np.mean(white)<.17:continue
        possible.append((x,y,w,h,area))
    if not possible:return None
    # If two taped fingertips are visible, prefer their common bounding box.
    possible.sort(key=lambda q:q[4],reverse=True)
    a=possible[0];x,y,w,h,_=a
    if len(possible)>1:
        others=[b for b in possible[1:] if math.hypot((b[0]+b[2]/2)-(x+w/2),(b[1]+b[3]/2)-(y+h/2))<210]
        if others:
            b=others[0]
            x1=min(x,b[0]);y1=min(y,b[1]);x2=max(x+w,b[0]+b[2]);y2=max(y+h,b[1]+b[3])
            pad=max(28,int(.28*max(x2-x1,y2-y1)))
            return clip_box((x1-pad,y1-pad,x2+pad,y2+pad),W,H)
    return clip_box((x-65,y-75,x+w+65,y+h+75),W,H)


class DetectorWorker:
    """Never blocks webcam rendering. Always processes the newest frame only."""
    def __init__(self,args):
        self.args=args;self.lock=threading.Lock();self.pending=None
        self.objects=[];self.updated=0.;self.processing=0.;self.error=None
        self.active=True
        self.thread=threading.Thread(target=self.run,daemon=True);self.thread.start()

    def offer(self,frame):
        with self.lock:self.pending=frame.copy()

    def read(self):
        with self.lock:return self.objects,self.updated,self.processing,self.error

    def run(self):
        try:
            import torch
            if not torch.cuda.is_available():torch.set_num_threads(min(4,max(1,torch.get_num_threads())))
            from ultralytics import YOLOWorld
            model=YOLOWorld('yolov8s-worldv2.pt')
            model.set_classes(DETECTION_LABELS)
            material=AppearanceGuard()
            surface=SurfaceClassifier(self.args.surface_res)
            while self.active:
                with self.lock:frame=self.pending;self.pending=None
                if frame is None:time.sleep(.009);continue
                t0=time.perf_counter();H,W=frame.shape[:2]
                prediction=model.predict(frame,conf=self.args.conf,imgsz=self.args.imgsz,
                                         verbose=False,max_det=24)[0]
                raw=[]
                if prediction.boxes is not None:
                    for d in prediction.boxes:
                        idx=int(d.cls.item())
                        if idx not in CLASS_KIND:continue
                        box=clip_box(d.xyxy[0].tolist(),W,H)
                        if min(box[2]-box[0],box[3]-box[1])<16:continue
                        raw.append({'kind':CLASS_KIND[idx], 'box':box,
                                    'conf':float(d.conf.item())})
                # Resolve ambiguous classes with structure/material checks.
                for item in raw:
                    if item['kind'] not in ('bagel','tub'):continue
                    info=material.inspect(frame,item['box'])
                    item['appearance']=info
                    if item['kind']=='tub' and info['bread']>.55 and info['bread']>info['tub']+.10:
                        item['kind']='bagel';item['source']='reclassified from tub'
                    elif item['kind']=='bagel' and info['tub']>.66 and info['bread']<.34:
                        item['kind']='tub';item['source']='reclassified from bagel'
                    # Reject unverified cream-cheese tub claims.
                    if item['kind']=='tub' and not (info['tub']>.22 and info['bread']<.59):
                        item['kind']='other'
                raw.sort(key=lambda x:x['conf'],reverse=True)
                final=[]
                for item in raw:
                    if item['kind']=='other':continue
                    if any(iou(item['box'],a['box'])>.48 for a in final):continue
                    final.append(item)
                    if len(final)>=self.args.max_objects:break
                bagels=[o for o in final if o['kind']=='bagel']
                claws=[o for o in final if o['kind']=='claw']
                if not claws:
                    fallback=gripper_fallback(frame)
                    if fallback is not None:
                        c={'kind':'claw candidate','box':fallback,'conf':0.}
                        final.append(c);claws=[c]
                knives=[o for o in final if o['kind']=='knife']
                # Shared tool is hard to localize; add line-candidate only with
                # a recognized claw as anchor. Explicitly NOT a confirmed knife.
                if claws and not knives:
                    claw=max(claws,key=lambda x:x['conf'])
                    bagel=max(bagels,key=lambda x:x['conf'])['box'] if bagels else None
                    line=candidate_knife_lines(frame,claw['box'],bagel)
                    if line:
                        px=[line[0][0],line[1][0]];py=[line[0][1],line[1][1]]
                        b=(max(0,min(px)-7),max(0,min(py)-7),min(W,max(px)+8),min(H,max(py)+8))
                        final.append({'kind':'tool candidate','box':b,'conf':0.,'line':line})
                for item in final:
                    if item['kind']=='bagel':
                        item['surface']=surface.analyze(frame,item['box'],self.args.spread_sensitivity)
                    if item['kind']=='knife':
                        item['line']=candidate_knife_lines(frame,item['box'],None)
                with self.lock:
                    self.objects=final;self.updated=time.monotonic();self.processing=time.perf_counter()-t0
        except Exception as e:
            with self.lock:self.error=f'{type(e).__name__}: {e}'

    def close(self):
        self.active=False;self.thread.join(timeout=2)


def draw(frame,objects,args):
    bagels=[o for o in objects if o['kind']=='bagel']
    knives=[o for o in objects if o['kind'] in ('knife','tool candidate')]
    claws=[o for o in objects if o['kind'] in ('claw','claw candidate')]
    for item in objects:
        kind=item['kind'];box=item['box'];x1,y1,x2,y2=box
        color=PALETTE.get(kind,(80,80,240))
        if kind=='bagel' and item.get('surface') is not None:
            mask,shape,pct=item['surface']
            roi=frame[y1:y2,x1:x2]
            if roi.shape[:2]==mask.shape:
                a=(mask>0)&(shape>0);b=(mask==0)&(shape>0)
                if a.any():roi[a]=(roi[a].astype(np.float32)*.58+np.array(GREEN)*.42).astype(np.uint8)
                if b.any():roi[b]=(roi[b].astype(np.float32)*.78+np.array(ORANGE)*.22).astype(np.uint8)
                border=cv2.Canny(mask,50,120)
                roi[(border>0)&(shape>0)]=(255,255,255)
            label=f'BAGEL | spread {pct}% / bare {100-pct}% est.'
        elif kind=='tub':
            info=item.get('appearance',{})
            label=f'CREAM CHEESE TUB (candidate) | features {info.get("tub",0):.2f}'
        elif kind=='tool candidate':label='POSSIBLE BLADE LINE (unverified)'
        elif kind=='claw candidate':label='CLAW CANDIDATE (green tip + white structure)'
        else:label=f'{kind.upper()} | detector {100*item["conf"]:.0f}%'
        cv2.rectangle(frame,(x1,y1),(x2,y2),color,2)
        cv2.putText(frame,label,(max(2,x1),max(60,y1-8)),cv2.FONT_HERSHEY_SIMPLEX,.48,(0,0,0),3,cv2.LINE_AA)
        cv2.putText(frame,label,(max(2,x1),max(60,y1-8)),cv2.FONT_HERSHEY_SIMPLEX,.48,color,1,cv2.LINE_AA)
        if item.get('line'):
            a,b=item['line'];cv2.line(frame,a,b,(20,20,255),2)
            cv2.circle(frame,a,4,(255,255,255),-1);cv2.circle(frame,b,4,(255,255,255),-1)
        if kind in ('claw','claw candidate','knife','tool candidate'):
            p=center(box);cv2.drawMarker(frame,p,color,cv2.MARKER_CROSS,12,2)
    if not bagels:status='BAGEL NOT CONFIRMED'
    elif not knives:status='KNIFE NOT CONFIRMED - NO CONTACT INFERENCE'
    else:
        target=max(bagels,key=lambda o:o['conf'])['box']
        line=knives[0].get('line')
        distance=min(distance_to_rect(point,target) for point in line) if line else distance_to_rect(center(knives[0]['box']),target)
        status=('2D TOOL/BAGEL OVERLAP - VERIFY DEPTH BEFORE MOVEMENT' if distance<=args.near_px
                else f'2D TOOL/BAGEL DISTANCE: {distance:.0f} px (not contact)')
    cv2.rectangle(frame,(0,0),(frame.shape[1],38),(15,15,15),-1)
    cv2.putText(frame,status[:94],(10,26),cv2.FONT_HERSHEY_SIMPLEX,.49,(250,250,250),1,cv2.LINE_AA)


def main():
    p=argparse.ArgumentParser(description='Automatic live bagel, tub and robot tool vision')
    p.add_argument('--camera',type=int,default=0)
    p.add_argument('--width',type=int,default=960)
    p.add_argument('--height',type=int,default=540)
    p.add_argument('--imgsz',type=int,default=416)
    p.add_argument('--surface-res',type=int,default=220)
    p.add_argument('--spread-sensitivity',type=float,default=.56)
    p.add_argument('--conf',type=float,default=.13)
    p.add_argument('--every',type=int,default=6)
    p.add_argument('--max-objects',type=int,default=8)
    p.add_argument('--near-px',type=float,default=16)
    p.add_argument('--stale',type=float,default=1.7)
    p.add_argument('--output',default='captures')
    args=p.parse_args()
    if args.every<1 or args.surface_res<60 or args.imgsz<128 or not .04<=args.conf<=1:
        p.error('Invalid parameter value')
    backend=cv2.CAP_DSHOW if sys.platform=='win32' else cv2.CAP_ANY
    cap=cv2.VideoCapture(args.camera,backend)
    if not cap.isOpened():raise SystemExit('Cannot open camera. Try --camera 1.')
    cap.set(cv2.CAP_PROP_FRAME_WIDTH,args.width)
    cap.set(cv2.CAP_PROP_FRAME_HEIGHT,args.height)
    cap.set(cv2.CAP_PROP_BUFFERSIZE,1)
    worker=DetectorWorker(args)
    count=0;fps=0.;t=time.monotonic();nc=0
    try:
        while True:
            ok,frame=cap.read()
            if not ok:break
            count+=1;nc+=1;now=time.monotonic()
            if now-t>=1:fps=nc/(now-t);nc=0;t=now
            if count==1 or count%args.every==0:worker.offer(frame)
            objs,updated,duration,error=worker.read()
            if error:
                print('Detection error:',error);break
            if updated and now-updated<args.stale:draw(frame,objs,args)
            else:
                cv2.rectangle(frame,(0,0),(frame.shape[1],38),(15,15,15),-1)
                cv2.putText(frame,'Loading / refreshing detections',(10,26),cv2.FONT_HERSHEY_SIMPLEX,.52,(255,255,255),1)
            msg=f'LIVE {fps:.0f} FPS | AI {duration:.2f}s | S save | Q quit | estimates only'
            cv2.putText(frame,msg,(9,frame.shape[0]-12),cv2.FONT_HERSHEY_SIMPLEX,.5,(255,255,255),2,cv2.LINE_AA)
            cv2.imshow('Bagel / Spread / Tub / Claw / Knife - AUTO V2',frame)
            key=cv2.waitKey(1)&255
            if key in (27,ord('q')):break
            if key==ord('s'):
                folder=Path(args.output);folder.mkdir(parents=True,exist_ok=True)
                dest=folder/('vision_'+time.strftime('%Y%m%d_%H%M%S')+'.jpg')
                cv2.imwrite(str(dest),frame);print('Saved:',dest)
    finally:
        worker.close();cap.release();cv2.destroyAllWindows()

if __name__=='__main__':main()
